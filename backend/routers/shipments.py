"""Shipment Tracker — 40' container collection + packing.

Admins (and only admins) manage a shipment. Anyone with the shareable token can:
  • view the wishlist (still needed + already acquired)
  • mark items as donated, optionally with a donor name (no auth, no email)
  • watch the running shipment weight + 40' container cap

AI packing scenarios are generated by Gemini-3-flash from the live item/pallet
state — text-only, fits inside a Markdown box on both the admin + public UIs.

40' high-cube container reference:
  Internal:  12.03 m × 2.35 m × 2.69 m   (≈ 76 m³)
  Max payload: ~26,000 kg
"""
from fastapi import APIRouter, Depends, HTTPException
from deps import db, get_current_user, _audit, require_admin, logger
from datetime import datetime, timezone
from typing import Optional
import uuid
import secrets

router = APIRouter(prefix="/api", tags=["shipments"])

# 40' high-cube interior dimensions in cm — used in the AI packing prompt.
CONTAINER_40FT_HC = {"length_cm": 1203, "width_cm": 235, "height_cm": 269, "max_payload_kg": 26000}

VALID_PRIORITIES = {"low", "normal", "high", "urgent"}
VALID_STATUSES = {"planning", "collecting", "packed", "shipped", "delivered", "cancelled"}


