@router.put("/shipments/{shipment_id}")
async def update_shipment(shipment_id: str, data: dict, current_user: dict = Depends(require_admin)):
    allowed = {"name", "dest_country", "description", "target_ship_date", "status", "max_payload_kg"}
    update = {k: v for k, v in data.items() if k in allowed}
    if "status" in update and update["status"] not in VALID_STATUSES:
        raise HTTPException(status_code=400, detail=f"status must be one of {sorted(VALID_STATUSES)}")
    update["updated_at"] = datetime.now(timezone.utc).isoformat()
    r = await db.shipments.update_one({"id": shipment_id}, {"$set": update})
    if r.matched_count == 0:
        raise HTTPException(status_code=404, detail="Shipment not found")
    return await db.shipments.find_one({"id": shipment_id}, {"_id": 0})


