def _normalise_item(data: dict) -> dict:
    """Coerce + clamp item fields. Used by both create and bulk-import."""
    name = (data.get("name") or "").strip()
    if not name:
        raise HTTPException(status_code=400, detail="item.name is required")
    priority = (data.get("priority") or "normal").lower()
    if priority not in VALID_PRIORITIES:
        priority = "normal"
    return {
        "id": f"sit_{uuid.uuid4().hex[:8]}",
        "name": name[:160],
        "category": (data.get("category") or "")[:60],
        "qty_needed": max(1, int(data.get("qty_needed") or 1)),
        "qty_acquired": max(0, int(data.get("qty_acquired") or 0)),
        "weight_kg": max(0, float(data.get("weight_kg") or 0)),
        "dims_cm": {
            "length": max(0, float((data.get("dims_cm") or {}).get("length") or 0)),
            "width": max(0, float((data.get("dims_cm") or {}).get("width") or 0)),
            "height": max(0, float((data.get("dims_cm") or {}).get("height") or 0)),
        },
        "photo_url": (data.get("photo_url") or "")[:500],
        "value_usd": max(0, float(data.get("value_usd") or 0)),
        "notes": (data.get("notes") or "")[:500],
        "priority": priority,
        "pallet_id": data.get("pallet_id") or None,
        "donations": [],
        "created_at": datetime.now(timezone.utc).isoformat(),
    }


@router.post("/shipments/{shipment_id}/items")
async def add_item(shipment_id: str, data: dict, current_user: dict = Depends(require_admin)):
    item = _normalise_item(data)
    r = await db.shipments.update_one({"id": shipment_id}, {"$push": {"items": item}})
    if r.matched_count == 0:
        raise HTTPException(status_code=404, detail="Shipment not found")
    return item


@router.put("/shipments/{shipment_id}/items/{item_id}")
async def update_item(shipment_id: str, item_id: str, data: dict, current_user: dict = Depends(require_admin)):
    allowed = {"name", "category", "qty_needed", "qty_acquired", "weight_kg",
               "dims_cm", "photo_url", "value_usd", "notes", "priority", "pallet_id"}
    set_ops = {}
    for k, v in data.items():
        if k not in allowed:
            continue
        # Clamp numeric fields just like create
        if k in ("qty_needed",):
            set_ops[f"items.$.{k}"] = max(1, int(v or 1))
        elif k in ("qty_acquired",):
            set_ops[f"items.$.{k}"] = max(0, int(v or 0))
        elif k in ("weight_kg", "value_usd"):
            set_ops[f"items.$.{k}"] = max(0, float(v or 0))
        elif k == "priority":
            p = (v or "normal").lower()
            set_ops[f"items.$.{k}"] = p if p in VALID_PRIORITIES else "normal"
        else:
            set_ops[f"items.$.{k}"] = v
    set_ops["items.$.updated_at"] = datetime.now(timezone.utc).isoformat()
    r = await db.shipments.update_one(
        {"id": shipment_id, "items.id": item_id},
        {"$set": set_ops},
    )
    if r.matched_count == 0:
        raise HTTPException(status_code=404, detail="Item not found")
    return {"updated": True}


